#!/usr/bin/env bun
/**
 * The settings table (docs/settings.md), generated from the settings loaders: every name a loader reads from the
 * environment, with its default and its one-line note. --write regenerates the file; --check (a step of make docs-check)
 * fails when the file is not what the loaders say, naming each name the table lacks and each row no loader declares.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const ROOT = join(import.meta.dir, '..')
const TABLE = join(ROOT, 'docs', 'settings.md')
const LOADERS = new Bun.Glob('apps/*/src/**/*.ts')
const BT = String.fromCharCode(96)
const KEY = /^(\s+)([A-Z][A-Z0-9_]*):\s/

export interface Setting {
  name: string
  defaultValue: string
  tunes: string
  loader: string
}

const plain = (text: string): string =>
  text
    .split(BT)
    .join('')
    .replace(/\$\{e\.HOME\}/g, '$HOME')
    .replace(/\$\{([^}]+)\}/g, '$1')

/** The expression starting at a position: up to a comma or semicolon, or the bracket that closes the call around it. */
export function expressionAt(text: string, start: number): string {
  let depth = 0
  let out = ''
  for (const c of text.slice(start)) {
    if (c === '\n') break
    if ('([{'.includes(c)) depth++
    if (')]}'.includes(c)) {
      if (depth === 0) break
      depth--
    }
    if (depth === 0 && (c === ',' || c === ';')) break
    out += c
  }
  return out.trim()
}

/** The loader's own expression for a key: a zod default, else its ?? fallback, else whether it is optional. */
export function defaultOf(src: string, value: string, chunk: string, key: string): string {
  const zod = chunk.indexOf('.default(')
  if (zod !== -1) return plain(expressionAt(chunk, zod + '.default('.length))
  const fallback = new RegExp(['\\b\\w+\\.', key, '\\s*\\?\\?\\s*'].join('')).exec(src)
  if (fallback) return plain(expressionAt(src, fallback.index + fallback[0].length))
  if (value.startsWith('Every(')) return plain(/'([^']+)'/.exec(value)?.[1] ?? value)
  if (chunk.includes('.optional()')) return 'unset'
  return 'required'
}

/** The note above a key: its one-line or multi-line doc comment, the first sentence of it. */
export function noteAbove(lines: string[], i: number): string {
  const above = (lines[i - 1] ?? '').trim()
  if (!above.endsWith('*/')) return ''
  let start = i - 1
  while (start > 0 && !(lines[start] ?? '').trim().startsWith('/**')) start--
  const text = lines
    .slice(start, i)
    .map((line) => line.replace(/^\s*\/\*\*|\*\/\s*$|^\s*\*\s?/g, ''))
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim()
  return text.split(/(?<=\.)\s/)[0] ?? ''
}

/** The settings one loader declares, in the order it declares them; a name declared twice in one loader is listed once. */
export function settingsOf(src: string, loader: string): Setting[] {
  const lines = src.split('\n')
  const seen = new Set<string>()
  const found: Setting[] = []
  lines.forEach((line, i) => {
    const key = KEY.exec(line)?.[2]
    if (!key || seen.has(key)) return
    seen.add(key)
    const value = line
      .slice(line.indexOf(':') + 1)
      .trim()
      .replace(/,$/, '')
    const next = lines.findIndex((l, j) => j > i && KEY.test(l))
    const chunk = lines.slice(i, next === -1 ? i + 4 : Math.min(next, i + 4)).join('\n')
    found.push({ name: key, defaultValue: defaultOf(src, value, chunk, key), tunes: noteAbove(lines, i), loader })
  })
  return found
}

/** A loader is a file that parses the environment with parseEnv (its definition in kernel/env.ts does not count). */
export function isLoader(src: string): boolean {
  return /(?<!function )parseEnv\(/.test(src)
}

/** Every setting of every loader under apps/<app>/src, sorted by name. */
export async function collect(): Promise<Setting[]> {
  const files: string[] = []
  for await (const path of LOADERS.scan({ cwd: ROOT })) {
    if (isLoader(readFileSync(join(ROOT, path), 'utf8'))) files.push(path)
  }
  const all: Setting[] = []
  for (const path of files.sort()) {
    all.push(...settingsOf(readFileSync(join(ROOT, path), 'utf8'), path))
  }
  return all.sort((a, b) => a.name.localeCompare(b.name) || a.loader.localeCompare(b.loader))
}

const cell = (text: string): string => text.split('|').join('\\|')
const code = (text: string): string => BT + cell(text) + BT

export function render(settings: Setting[]): string {
  const rows = settings.map((s) => {
    const dflt = ['unset', 'required'].includes(s.defaultValue) ? s.defaultValue : code(s.defaultValue)
    return ['| ', code(s.name), ' | ', dflt, ' | ', cell(s.tunes), ' | ', code(s.loader), ' |'].join('')
  })
  const intro = [
    'Every name a settings loader reads from the environment: its default in the code (or ',
    code('unset'),
    ' when optional, ',
    code('required'),
    ' when the loader refuses to start without it) and what it tunes. Generated by ',
    code('scripts/settings-table.ts'),
    ' from the loaders: do not edit it by hand. After a loader changes, run ',
    code('bun scripts/settings-table.ts --write'),
    '; make docs-check fails until it does. Prose names a setting by linking here.',
  ].join('')
  return ['# Settings', '', intro, '', '| Name | Default | What it tunes | Loader |', '|-|-|-|-|', ...rows, ''].join(
    '\n',
  )
}

/** The names a table lists in its first column. */
export function namesIn(table: string): string[] {
  const row = new RegExp(['^\\| ', BT, '([A-Z][A-Z0-9_]*)', BT, ' \\|'].join(''), 'gm')
  return [...table.matchAll(row)].map((m) => m[1] ?? '')
}

/** Every reason the committed table disagrees with the loaders; empty when it is what they say. */
export function problemsIn(table: string, declared: Setting[]): string[] {
  const listed = new Set(namesIn(table))
  const names = new Set(declared.map((s) => s.name))
  const problems = declared
    .filter((s) => !listed.has(s.name))
    .map((s) => ['docs/settings.md lacks ', s.name, ' (declared in ', s.loader, ')'].join(''))
  for (const name of listed) {
    if (!names.has(name)) problems.push(['docs/settings.md names ', name, ', which no loader declares'].join(''))
  }
  if (!problems.length && table !== render(declared)) {
    problems.push('docs/settings.md is stale: run bun scripts/settings-table.ts --write')
  }
  return [...new Set(problems)]
}

async function main(): Promise<number> {
  const mode = process.argv[2]
  const declared = await collect()
  if (mode === '--write') {
    writeFileSync(TABLE, render(declared))
    console.log(['wrote ', relative(ROOT, TABLE), ': ', String(declared.length), ' settings'].join(''))
    return 0
  }
  if (mode !== '--check') {
    console.error('usage: bun scripts/settings-table.ts --write | --check')
    return 2
  }
  const table = existsSync(TABLE) ? readFileSync(TABLE, 'utf8') : ''
  const problems = problemsIn(table, declared)
  for (const problem of problems) console.error(problem)
  if (problems.length) return 1
  console.log(['settings table: ', String(declared.length), ' settings, all listed'].join(''))
  return 0
}

if (import.meta.main) process.exit(await main())
