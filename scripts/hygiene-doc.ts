#!/usr/bin/env bun
/**
 * Writes `docs/hygiene.md` from the hygiene catalogue (`packages/contract/src/hygiene-catalogue.ts`), the one list the page,
 * the Console's project Hygiene tab and `factory read project-hygiene` all render. `--check` compares instead of writing and
 * exits 1 when the page is stale; `make check` runs it that way, so a probe added to the catalogue without regenerating fails.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import {
  type HygieneCatalogueEntry,
  HYGIENE_CATALOGUE,
  type PROBE_COSTS,
} from '../packages/contract/src/hygiene-catalogue.ts'

const ROOT = join(import.meta.dir, '..')
export const PAGE_FILE = join(ROOT, 'docs', 'hygiene.md')

const ENABLED: Record<HygieneCatalogueEntry['enabled'], string> = {
  on: 'on for every project',
  auto: 'on when detection finds what it reads',
  'opt-in': 'only where the project asks',
}
const COST: Record<(typeof PROBE_COSTS)[number], string> = {
  file: 'reads tracked files',
  tool: 'runs an analyzer or asks a registry',
  make: "runs the project's own make target",
  agent: 'one model call on the cheap seat',
}

const summaryTable = (): string =>
  [
    '| Probe | Default | Runs | Cost |',
    '|-|-|-|-|',
    ...HYGIENE_CATALOGUE.map(
      (entry) => `| [\`${entry.name}\`](#${entry.name}) | ${entry.enabled} | ${entry.cadence} | ${entry.cost} |`,
    ),
  ].join('\n')

const section = (entry: HygieneCatalogueEntry): string =>
  [
    `### ${entry.name}`,
    '',
    entry.summary,
    '',
    `- **Default:** ${ENABLED[entry.enabled]}${entry.detect ? `: ${entry.detect}` : ''}.`,
    `- **Runs:** ${entry.cadence === 'daily' ? 'in the daily pass and the weekly one' : 'in the weekly pass'}; ${COST[entry.cost]}.`,
    `- **Silence it:** ${entry.silence}`,
  ].join('\n')

/** The whole page. */
export function pageText(): string {
  return `# Hygiene

<!-- generated by scripts/hygiene-doc.ts from packages/contract/src/hygiene-catalogue.ts: edit the catalogue, then \`bun scripts/hygiene-doc.ts\` -->

Hygiene is the factory's standing check on a project's health: probes read a throwaway checkout of the default branch, and
what they find becomes a signal, then an Issue like any other. The probes are one catalogue in code. This page, the project
page's Hygiene tab and \`factory read project-hygiene <name>\` render that one list, so they cannot disagree.

## How a pass runs

| Pass | When | What runs |
|-|-|-|
| Weekly (full) | a project's newest full pass is a week old, or sooner for a busy repo | every probe the project has on, the project's own probes, and the document judgment |
| Daily | the newest pass of any scope is a day old | only the probes marked \`daily\` below, no judgment |

- **A busy repo goes sooner.** A daily pass becomes a full one when 30 or more commits landed since the last full pass and that
  pass is at least two days old.
- **One project per tick.** Full passes come before daily ones, never-swept projects first, then the oldest.
- **Budget.** At most 3 probe findings and 5 signals in all per pass, probes ranked in the catalogue's order; the rest are
  named in the pass record, never dropped. A finding class that mostly ends dropped or cancelled stops filing for 14 days.
- **Settings.** \`FACTORY_HYGIENE_EVERY_MS\` (the week), \`FACTORY_HYGIENE_DAILY_MS\` (the day, 0 turns daily passes off),
  \`FACTORY_HYGIENE_RETRY_MS\`, \`FACTORY_HYGIENE_REPOS\` (\`apps/server/src/app/loops/settings.ts\`, set in the env file).
- **The seat.** Every signal carries a \`Seat:\` line. A finding's Issue starts on the light seat whatever its size: the probe that
  found it turning green proves the fix, and a light lead that struggles is moved up once. A class whose Issues keep moving up
  (its move-up share over its last 20 Issues above the bound the cost of a move-up sets) starts on the standard lead until the
  share drops under it; \`factory read finding-classes\` shows each class's starts, move-ups and pass rate, and which are out.

## What happens to a finding

A finding is its key (\`links:docs/a.md\`, \`check\`) and the Issues that key filed. Its state is read from the newest of
those Issues and from the next pass's verdict, never stored.

| The probe says | The newest Issue of the key is | The pass does |
|-|-|-|
| red | none, or closed healed, dropped or cancelled | files a signal (a new Issue) |
| red | open | nothing: the Issue is the finding's life |
| red | closed done, within 29 days | reopens that Issue with the evidence; no second Issue |
| red | closed done and already reopened twice | leaves it to a person, and says so on the Hygiene tab |
| green (ran, did not raise the key) | queued or settling: no lead has started | closes it as healed, with the probe's run as the reason |
| green | a lead is working or waiting | tells the lead once; the lead decides |
| green | in its Watch, or closed | nothing |

A run that was skipped or failed says nothing about a key, so it never heals. The document judgment never heals: it reads a
few documents, and absence proves nothing. Every action is recorded on the pass and listed on the Hygiene tab.

## The catalogue

${summaryTable()}

${HYGIENE_CATALOGUE.map(section).join('\n\n')}

## For a repo author

- **See what runs.** \`factory read project-hygiene <name>\` or the project's Hygiene tab: each probe with its last run,
  the findings that stand and what became of each.
- **Silence a probe** with its reason; the reason is required and the pass shows it:

\`\`\`yaml
hygiene:
  skip:
    - { probe: deadcode, reason: generated code is imported by the build, not by source }
  check: false # the gate needs a lab this host lacks
  reason: needs the device farm
\`\`\`

- **Add your own probe**: a make target that exits 0 when green, and \`hygiene: { probes: [{ name, target }] }\`. It runs weekly,
  one finding \`probe:<name>\` with the output tail.
- **Clear a finding.** Fix what it names, or for a false positive silence the probe with a reason, or close its Issue as
  dropped with the reason (a class that is mostly dropped stops filing).
- **Check the project file before you push** with \`factory project check\`: it is the lint the \`project\` probe runs.
- **Coverage** is not a built-in probe. A repo that wants it declares a probe whose target fails under a floor.
`
}

async function main(check: boolean): Promise<number> {
  const next = pageText()
  const current = await readFile(PAGE_FILE, 'utf8').catch(() => '')
  if (check) {
    if (current === next) return 0
    console.error('stale: docs/hygiene.md; run `bun scripts/hygiene-doc.ts` and commit the result')
    return 1
  }
  await writeFile(PAGE_FILE, next)
  return 0
}

if (import.meta.main) process.exit(await main(process.argv.includes('--check')))
