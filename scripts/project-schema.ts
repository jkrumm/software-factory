#!/usr/bin/env bun
/**
 * Writes the two files generated from `project.yaml`'s schema (`packages/contract/src/project-file.ts`):
 * `schema/project.schema.json`, the JSON Schema an editor reads, and the key reference of `docs/project.md` (between its
 * `keys:start` and `keys:end` markers). `--check` compares instead of writing and exits 1 when either is stale; `make
 * check` runs it that way, so a key added to the schema without regenerating fails the check.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { projectJsonSchema } from '../packages/contract/src/project-file.ts'

const ROOT = join(import.meta.dir, '..')
export const SCHEMA_FILE = join(ROOT, 'schema', 'project.schema.json')
export const PAGE_FILE = join(ROOT, 'docs', 'project.md')
const START =
  '<!-- keys:start (generated by scripts/project-schema.ts; edit the schema, then `bun scripts/project-schema.ts`) -->'
const END = '<!-- keys:end -->'

type Json = Record<string, unknown>
const isJson = (value: unknown): value is Json => typeof value === 'object' && value !== null && !Array.isArray(value)

export const schemaText = (): string => `${JSON.stringify(projectJsonSchema(), null, 2)}\n`

/** One row of the reference: a key's dotted path and what the schema says of it. */
export interface KeyRow {
  path: string
  type: string
  default: string
  consumer: string
  description: string
  deprecated: boolean
}

const DURATION_PATTERN = '^(\\d+)(s|m|h|d)$'

function resolve(schema: Json, root: Json): Json {
  const ref = schema.$ref
  if (typeof ref !== 'string') return schema
  const name = ref.replace(/^#\/definitions\//, '')
  const target = (root.definitions as Json | undefined)?.[name]
  return isJson(target) ? { ...target, ...schema, $ref: undefined } : schema
}

function typeOf(raw: Json, root: Json): string {
  const schema = resolve(raw, root)
  if (Array.isArray(schema.anyOf)) {
    const parts = schema.anyOf.filter(isJson).map((part) => typeOf(part, root))
    return [...new Set(parts)].join(' or ')
  }
  if ('const' in schema) return `\`${String(schema.const)}\``
  if (Array.isArray(schema.enum)) return schema.enum.map((value) => `\`${String(value)}\``).join(', ')
  switch (schema.type) {
    case 'string':
      return schema.pattern === DURATION_PATTERN
        ? 'duration'
        : String(schema.pattern ?? '').includes('MiB|GiB')
          ? 'size'
          : String(schema.pattern ?? '').includes('%')
            ? 'share'
            : 'string'
    case 'integer': {
      const range =
        typeof schema.minimum === 'number' && typeof schema.maximum === 'number'
          ? ` ${schema.minimum}–${schema.maximum}`
          : ''
      return `integer${range}`
    }
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array':
      return isJson(schema.items) ? `list of ${typeOf(schema.items, root)}` : 'list'
    case 'object':
      if (isJson(schema.properties)) return 'object'
      if (isJson(schema.additionalProperties)) return `map of ${typeOf(schema.additionalProperties, root)}`
      return 'object'
    default:
      return 'any'
  }
}

/** The object schemas a key's value can be: itself, an array's items, a record's values, each branch of a union. */
function objectsOf(raw: Json, root: Json): { schema: Json; suffix: string }[] {
  const schema = resolve(raw, root)
  if (Array.isArray(schema.anyOf)) return schema.anyOf.filter(isJson).flatMap((part) => objectsOf(part, root))
  if (schema.type === 'array' && isJson(schema.items)) {
    return objectsOf(schema.items, root).map((found) => ({ ...found, suffix: `[]${found.suffix}` }))
  }
  if (schema.type === 'object' && isJson(schema.properties)) return [{ schema, suffix: '' }]
  if (schema.type === 'object' && isJson(schema.additionalProperties)) {
    return objectsOf(schema.additionalProperties, root).map((found) => ({ ...found, suffix: `.<name>${found.suffix}` }))
  }
  return []
}

/** Every key of the schema, depth first, with its type, default, consumer and description. */
export function keyRows(root: Json = projectJsonSchema()): KeyRow[] {
  const rows: KeyRow[] = []
  const walk = (object: Json, prefix: string) => {
    const required = new Set(Array.isArray(object.required) ? object.required : [])
    for (const [key, raw] of Object.entries(isJson(object.properties) ? object.properties : {})) {
      if (!isJson(raw)) continue
      const path = `${prefix}${key}`
      const schema = resolve(raw, root)
      rows.push({
        path,
        type: typeOf(schema, root),
        default: required.has(key) ? 'required' : 'default' in schema ? `\`${JSON.stringify(schema.default)}\`` : '—',
        consumer: typeof schema.consumer === 'string' ? schema.consumer : '—',
        description: typeof schema.description === 'string' ? schema.description : '',
        deprecated: schema.deprecated === true,
      })
      for (const found of objectsOf(schema, root)) walk(found.schema, `${path}${found.suffix}.`)
    }
  }
  walk(root, '')
  return rows
}

const cell = (text: string): string => text.replaceAll('|', '\\|').replaceAll('\n', ' ')

/** The key reference: one table row per key, retired keys last. */
export function referenceText(rows: readonly KeyRow[] = keyRows()): string {
  const line = (row: KeyRow) =>
    `| \`${row.path}\` | ${cell(row.type)} | ${cell(row.default)} | ${cell(row.consumer)} | ${cell(row.description)} |`
  const live = rows.filter((row) => !row.deprecated)
  const retired = rows.filter((row) => row.deprecated)
  return [
    START,
    '',
    '| Key | Type | Default | Read by | What it means |',
    '|-|-|-|-|-|',
    ...live.map(line),
    '',
    'Retired keys: accepted and dropped so an older file still parses, read by nothing; `factory project check` warns on each.',
    '',
    '| Key | Type | Default | Read by | What it means |',
    '|-|-|-|-|-|',
    ...retired.map(line),
    '',
    END,
  ].join('\n')
}

/** The page with its reference replaced; `null` when the markers are missing. */
export function pageWithReference(page: string, reference: string = referenceText()): string | null {
  const start = page.indexOf(START)
  const end = page.indexOf(END)
  if (start === -1 || end === -1 || end < start) return null
  return `${page.slice(0, start)}${reference}${page.slice(end + END.length)}`
}

async function main(check: boolean): Promise<number> {
  const page = await readFile(PAGE_FILE, 'utf8')
  const nextPage = pageWithReference(page)
  if (nextPage === null) {
    console.error(`${PAGE_FILE}: the keys:start and keys:end markers are missing`)
    return 1
  }
  const nextSchema = schemaText()
  const currentSchema = await readFile(SCHEMA_FILE, 'utf8').catch(() => '')
  if (check) {
    const stale = [
      ...(currentSchema === nextSchema ? [] : ['schema/project.schema.json']),
      ...(page === nextPage ? [] : ['docs/project.md (key reference)']),
    ]
    if (stale.length === 0) return 0
    console.error(`stale: ${stale.join(', ')}; run \`bun scripts/project-schema.ts\` and commit the result`)
    return 1
  }
  await writeFile(SCHEMA_FILE, nextSchema)
  await writeFile(PAGE_FILE, nextPage)
  return 0
}

if (import.meta.main) process.exit(await main(process.argv.includes('--check')))
